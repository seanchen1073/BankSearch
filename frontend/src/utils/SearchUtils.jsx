/**
 * 搜尋文字正規化
 *
 * 用於解決：
 * 臺灣銀行 = 台灣銀行
 * 玉山商業銀行 = 玉山
 * 第一銀行 = 第一
 */
export const normalizeKeyword = (text = "") => {
  return (
    String(text)
      .toLowerCase()

      // 繁簡 / 異體處理
      .replaceAll("臺", "台")

      // 名稱簡化
      .replaceAll("股份有限公司", "")
      .replaceAll("商業銀行", "")
      .replaceAll("銀行", "")

      // 移除空白
      .replaceAll(/\s/g, "")

      .trim()
  );
};

